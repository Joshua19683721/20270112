def clean(s):
    # 去掉模型吐出的提示詞殘渣
    s = re.sub(r'^(?:編號|碼|網友|詳解|答案|說明|正確答案|選項)\s*[.．、：:]\s*', '', s)
    s = re.sub(r'^(?:編號|碼|網友)\s*[.．、]\s*', '', s)
    s = re.sub(r'^詳解\s*[：:]\s*', '', s)
    s = re.sub(r'^(?:編號|碼|網友)\s*[.．、]\s*', '', s)
    s = re.sub(r'詳解\s*[：:]', '', s)
    for a, b in GLOBAL:
        s = s.replace(a, b)
    # 錯誤題若把原句照抄一遍，改成精簡說法
    s = re.sub(r'^錯誤，\s*', '', s)
    s = s.strip()
    if len(s) > 78:
        s = s[:76].rstrip('，、；') + '。'
    return s


out = {}
for k, v in w.items():
    lid, i = k.split('#')
    it = q[lid][int(i)]
    s = OVERRIDE.get(k, clean(v))
    if not s:
        s = ('課本重點：' + (it['o'][it['a']] if it['t'] == 'mc' else '這個敘述')) + '，請回到重點卡再看一次。'
    out[k] = s

json.dump(out, open(os.path.join(D, 'why_clean.json'), 'w', encoding='utf-8'),
          ensure_ascii=False, indent=1)
left = [k for k, v in out.items() if re.match(r'^(編號|碼|網友|詳解)', v)]
print('clean', len(out), 'leftover junk', len(left))
